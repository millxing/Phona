#!/usr/bin/env python3
"""Write rack-plugin/rust/src/beat_fit_table.rs from fit_<sound>.json and eval_<sound>.json.

Usage: table.py      (run from anywhere; reads the files beside this script)
The output gain of each sound sets its peak level: kick 0.6, snare 0.5, hat 0.3.
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parents[1] / "rack-plugin" / "rust" / "src" / "beat_fit_table.rs"
PEAK = {"B": 0.6, "Pf": 0.5, "t": 0.3}
ARTIC = {"jaw": "Jaw", "tbX": "TbX", "tbY": "TbY", "ttX": "TtX", "ttY": "TtY", "lipAp": "LipAp", "larynx": "Larynx", "labiodental": "Labiodental"}
SOURCE = {"abduction": "ABDUCTION", "breath": "BREATH", "closure": "CLOSURE"}
FIELD = {"t0": "Shift", "dur": "Dur", "ri": "RampIn", "ro": "RampOut", "str": "Strength", "spd": "Speed"}

def num(x):
    s = f"{x:.6g}"
    return s if any(c in s for c in ".e") else s + ".0"

def entry(sound):
    p = json.load(open(HERE / f"fit_{sound}.json"))["params"]
    ev = json.load(open(HERE / f"eval_{sound}.json"))["fitted"]
    peak = ev["peak"]
    g = lambda k, d: num(p.get(k, d))
    key = lambda name: f"ControlKey::Artic(ArticKey::{ARTIC[name]})" if name in ARTIC else f"ControlKey::{SOURCE[name]}"
    edits, extra = [], {}
    for k, x in p.items():
        if "." not in k or k[0] not in "gx":
            continue
        i, field = k[1:].split(".")
        if k[0] == "x":
            e = extra.setdefault(int(i), {"t0": 0.0, "dur": 50.0, "ri": 10.0, "ro": 20.0, "str": 40.0})
            if field in e:
                e[field] = x
            else:
                e["key"], e["value"] = key(field), x
            continue
        what = f"BeatEdit::{FIELD[field]}" if field in FIELD else f"BeatEdit::Target({key(field)})"
        edits.append(f"({i}, {what}, {num(x)})")
    extras = [f"BeatExtra {{ t0: {num(e['t0'])}, dur: {num(e['dur'])}, ramp_in: {num(e['ri'])}, ramp_out: {num(e['ro'])}, strength: {num(e['str'])}, key: {e['key']}, value: {num(e['value'])} }}"
              for _, e in sorted(extra.items())]
    lp = p.get("lp", 0.0)
    return (f"    // {sound}: loss {json.load(open(HERE / f'fit_{sound}.json'))['loss']:.2f}\n"
            f"    BeatFit {{\n"
            f"        noise: [{g('ng', 1)}, {g('nc', 1)}, {g('nt', 1)}],\n"
            f"        bands: [({g('bgl', 3500)}, {g('bgh', 300)}), ({g('bcl', 2600)}, {g('bch', 350)}), ({g('btl', 5000)}, {g('bth', 1200)})],\n"
            f"        pressure: {g('press', 8)},\n"
            f"        posture: [{g('pj', 0)}, {g('pl', 0)}, {g('pt', 0)}],\n"
            f"        hp: {g('hp', 0)},\n"
            f"        gain: {num(PEAK[sound] / peak)},\n"
            f"        shelf: ({g('shf', 120)}, {g('shg', 0)}),\n"
            f"        peak: ({g('pkf', 1000)}, {g('pkg', 0)}, {g('pkq', 1)}),\n"
            f"        lp: {num(lp)},\n"
            f"        viscous: {g('visc', 1)},\n"
            f"        edits: &[\n            " + ",\n            ".join(edits) + ",\n        ],\n"
            f"        extra: &[" + ", ".join(extras) + "],\n"
            f"        hold: {num(ev.get('hold_s', 0.0))},\n        tail: {num(ev.get('tail_s', 0.6))},\n    }},\n")

OUT.write_text("// Generated by audition/beat-fit-01/table.py from the fit results. Do not edit by hand.\n"
               "pub(crate) const BEAT_FIT: [BeatFit; 3] = [\n" + "".join(entry(s) for s in ["B", "Pf", "t"]) + "];\n")
print("wrote", OUT)
